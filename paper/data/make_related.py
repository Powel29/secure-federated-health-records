"""Generate paper/tables/related.tex (Table tab:related) from facts-F8.md.

Rival rows are parsed from the "Related-work matrix" in paper/notes/facts-F8.md
(first symbol of each cell). The "this work" row is filled from facts-live.md
and facts-F1/F2/F3/F6/F8; each cell names its source below.

Run: .venv/Scripts/python.exe paper/data/make_related.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / "notes" / "facts-F8.md"
OUT = ROOT / "tables" / "related.tex"

# Columns kept from the F8 matrix (FED dropped to fit \columnwidth).
COLUMNS = ["CE", "LG", "BG", "LC", "TB", "ES", "FP", "IMP"]

# F8 matrix row label -> (table label, group number for \midrule separators,
# numbered facts-F8 entry for the work, emitted as the row's % src: tag)
ROWS = {
    "Kroll et al. (n.d.)": (r"Kroll et al.~\cite{kroll2018accountable}", 1, 1),
    "Ryan 2017": (r"Ryan~\cite{ryan2017accountable}", 1, 2),
    "Cheval, Moreira, Ryan 2023": (r"Cheval et al.~\cite{cheval2023transparency}", 1, 3),
    "Ferreira et al. 2006": (r"Ferreira et al.~\cite{ferreira2006break}", 2, 7),
    "Brucker, Petritsch, Weber 2010": (r"Brucker et al.~\cite{brucker2010abe}", 3, 9),
    "Scafuro 2019": (r"Scafuro~\cite{scafuro2019breakglass}", 3, 11),
    "de Oliveira et al. 2020": (r"de Oliveira et al.~\cite{deoliveira2020breakglass}", 3, 13),
    "Li et al. TPDS 2013": (r"Li et al.~\cite{li2013phr}", 4, 15),
    "Yang & Ma 2016": (r"Yang, Ma~\cite{yang2016timing}", 5, 16),
    "Muslim & Grégoire 2026": (r"Muslim, Gr\'egoire~\cite{muslim2026consent}", 6, 17),
    "Romel et al. 2025": (r"Romel et al.~\cite{romel2025patient}", 6, 18),
}

SYMBOL = {
    "✓": r"$\checkmark$",
    "~": r"$\circ$",
    "✗": "--",
    "?": "?",
}

# "This work" row, from the live evidence (not from the review).
THIS_WORK = {
    # keys decide access; portals/DB never do: facts-F4#19, facts-F3#39
    "CE": r"$\checkmark$",
    # audit shares released only after assertion check + commit: facts-F2#50,
    # facts-F2#51, facts-live#2 (C2 holds); trusted log: facts-F2#59 -> note a
    "LG": r"$\checkmark^{a}$",
    # break-glass open via 3-of-4 gate: facts-F1#46, facts-live#3 (C3 holds)
    "BG": r"$\checkmark$",
    # partial: patient revocation is a signed lifecycle transition, but consent
    # is a patient-signed grant checked at read time when one is presented
    # (its own status, window and signature), separate from the lifecycle
    # state, not a transition (no grant emitter): facts-F1#11, facts-F1#35,
    # facts-F1#77, facts-F1#78 -> note b
    "LC": r"$\circ^{b}$",
    # 4 h window, expiry by full rotation, server-enforced: facts-F1#49,
    # facts-F1#39, facts-F1#54, facts-live#4 (C4 holds) -> note c
    "TB": r"$\checkmark^{c}$",
    # search tokens from the emergency key, end at expiry: facts-F3#51,
    # facts-F3#53, facts-F3#54, facts-live#4
    "ES": r"$\checkmark$",
    # no formal model, no log proofs: facts-F8#3, facts-F8#24
    "FP": "--",
    # implemented and tested: facts-live#12, facts-live#14
    "IMP": r"$\checkmark$",
}


def parse_matrix() -> dict[str, dict[str, str]]:
    text = FACTS.read_text(encoding="utf-8")
    section = text.split("## Related-work matrix", 1)[1].split("\n## ", 1)[0]
    header: list[str] | None = None
    rows: dict[str, dict[str, str]] = {}
    for line in section.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
            continue
        if set(cells[0]) <= {"-"}:
            continue
        name = cells[0]
        if name.startswith("**This work"):
            continue
        rows[name] = dict(zip(header[1:], cells[1:]))
    return rows


def symbol(cell: str) -> str:
    first = cell.split()[0] if cell else ""
    for key, sym in SYMBOL.items():
        if first.startswith(key):
            return sym
    raise ValueError(f"unrecognised matrix cell: {cell!r}")


def main() -> None:
    matrix = parse_matrix()
    missing = set(ROWS) - set(matrix)
    if missing:
        raise SystemExit(f"rows missing from facts-F8 matrix: {sorted(missing)}")

    lines = [
        "% Generated by paper/data/make_related.py from paper/notes/facts-F8.md",
        "% (rival rows) and facts-live/F1/F2/F3/F8 (this-work row). Do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Comparison with the closest related work (legend and notes below the table).}",
        r"\label{tab:related}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{2.4pt}",
        r"\begin{tabular}{@{}l" + "c" * len(COLUMNS) + "@{}}",
        r"\toprule",
        "Work & " + " & ".join(COLUMNS) + r" \\",
        r"\midrule",
    ]
    previous_group = None
    for name, (label, group, fact) in ROWS.items():
        if previous_group is not None and group != previous_group:
            lines.append(r"\midrule")
        previous_group = group
        cells = [symbol(matrix[name][col]) for col in COLUMNS]
        lines.append(f"{label} & " + " & ".join(cells) + rf" \\ % src: facts-F8#{fact}")
    lines.append(r"\midrule")
    lines.append(
        r"\textbf{This work} & "
        + " & ".join(THIS_WORK[col] for col in COLUMNS)
        + r" \\ % src: facts-live#12, facts-F1#11, facts-F1#35, facts-F1#54, facts-F1#77, facts-F1#78,"
        + " facts-F2#50, facts-F2#59, facts-F3#53, facts-F8#3"
    )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\vspace{3pt}",
        r"{\footnotesize\raggedright",
        r"\textit{Columns.} CE: keys, not a policy check, decide access;",
        r"LG: key release gated on a log entry; BG: break-glass;",
        r"LC: consent and revocation in one lifecycle; TB: time-boxed expiry;",
        r"ES: emergency-scoped or time-limited search; FP: formal proof or model;",
        r"IMP: implementation.\\",
        r"\textit{Marks.} $\checkmark$~yes; $\circ$~partial; --~no;",
        r"?~not determined from the paper.\\",
        r"\textit{This work.} Taken from our live test run",
        r"(Table~\ref{tab:claims}).\\",
        "% src: facts-live#12",
        r"$^{a}$~Trusted hash chain, no log proofs.\\",
        "% src: facts-F2#59, facts-F8#3",
        r"$^{b}$~Revocation is a lifecycle transition; consent is a patient-signed",
        r"grant checked at read time when presented, outside the lifecycle.\\",
        "% src: facts-F1#11, facts-F1#35, facts-F1#77, facts-F1#78",
        r"$^{c}$~Expiry is server-enforced, not cryptographic.\par}",
        "% src: facts-F1#54",
        r"\end{table}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(ROWS) + 1} rows)")


if __name__ == "__main__":
    main()
