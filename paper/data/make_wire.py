"""Generate paper/tables/wire.tex (label tab:wire) from the P5-5 wire checks.

Source: bench/results/p55_wire_checks.json, written by
`python -m wire.analyze_traffic` (facts-F6 §E-§G; run of 2026-10-21 at 99092d1,
no wire/src/deploy/tests/wire change since). Every number and pass/fail value
below is read from that file; only the short property names and the fixed
"n/a" wording (claims 2 and 3 take the plain capture only, wire/checks.py:298,
:470) are written here.

    .venv/Scripts/python.exe paper/data/make_wire.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "bench" / "results" / "p55_wire_checks.json"
OUT = ROOT / "paper" / "tables" / "wire.tex"

PROPERTY = {
    "0-preconditions": "Preconditions",
    "1-no-plaintext": "No plaintext",
    "2-commit-before-release": "Commit before release",
    "3-search-leakage": "Search leakage",
    "4-breakglass-metadata-only": "Break-glass as metadata",
}


def cells(c: dict) -> tuple[str, str]:
    ev = c["evidence"]
    name = c["claim"]
    if name == "0-preconditions":
        return (f"{len(ev['plain_endpoints_seen'])} endpoints seen", "TLS records only")
    if name == "1-no-plaintext":
        n_plain = len(ev["plain_hits"])
        n_tls = len(ev["tls_hits"])
        searched = ev["canaries_searched"]
        ctrl = "control fired" if ev["positive_control_fired"] else "control silent"
        return (
            f"{n_plain} of {searched['plain']} canaries hit ({ctrl})",
            f"{n_tls} of {searched['tls']} canaries hit",
        )
    if name == "2-commit-before-release":
        return (f"COMMIT {ev['commit_lead_ms']:.2f}\\,ms before response", "n/a (plain only)")
    if name == "3-search-leakage":
        p = ev["profile"]
        sizes = ", ".join(str(s) for s in p["distinct_response_sizes"])
        return (
            f"{p['query_volume']} search, {p['queries_visible_in_clear']} term in clear, "
            f"{sizes}\\,B resp.",
            "n/a (plain only)",
        )
    if name == "4-breakglass-metadata-only":
        burst = ev["tls_unlock_burst"]
        return (
            f"URI visible; {ev['plain_unlock_request_bytes']}\\,B request",
            f"{burst['bytes']}\\,B burst; {len(ev['breakglass_content_hits'])} content hits",
        )
    raise SystemExit(f"unknown claim {name!r}")


def main() -> None:
    checks = json.loads(SRC.read_text(encoding="utf-8"))
    if [c["claim"] for c in checks] != list(PROPERTY):
        raise SystemExit("unexpected claim list in p55_wire_checks.json")
    out = [
        "% Generated by paper/data/make_wire.py from bench/results/p55_wire_checks.json.",
        "% Do not edit by hand.",
        r"\begin{table}[!t]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        (
            r"\caption{PyShark wire checks on the plain and TLS captures "
            r"(captured 2026-10-21 on the tree committed as "
            r"\textnormal{\texttt{99092d1}}; no capture, analyser or service "
            r"code changed up to \textnormal{\texttt{57a1a8c}}).}"
        ),
        "% src: " + ", ".join(f"facts-F6#{i}" for i in range(34, 54))
        + ", facts-F6#90, facts-F6#93",
        r"\label{tab:wire}",
        r"\begin{tabular}{@{}l p{0.19\columnwidth} p{0.29\columnwidth} p{0.27\columnwidth} l@{}}",
        r"\toprule",
        r"\# & Property & Plain capture & TLS capture & Result \\",
        r"\midrule",
    ]
    for c in checks:
        num = c["claim"].split("-", 1)[0]
        plain, tls = cells(c)
        result = ("pass" if c["passed"] else "FAIL") + (
            "$^\\ast$" if c["strength"] == "measurement" else ""
        )
        out.append(f"{num} & {PROPERTY[c['claim']]} & {plain} & {tls} & {result} \\\\")
    out += [
        r"\bottomrule",
        r"\multicolumn{5}{@{}p{\columnwidth}@{}}{$^\ast$A measurement: it fails only "
        r"if no search traffic is captured.}\\",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({len(checks)} checks)")


if __name__ == "__main__":
    main()
