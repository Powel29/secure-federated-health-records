"""Generate paper/tables/transitions.tex from the shipped code and facts-F1 (W3).

The rows are not typed by hand. The set of (from, to) pairs is read from
``lifecycle.state_machine.LEGAL_TRANSITIONS`` (the code) and from the
transition table in ``paper/notes/facts-F1.md`` (fact 46), and the script
refuses to write anything unless the two sets are identical and each row's
signer(s) match the fact-46 "Signed by" column. The cell text is
a condensed wording of the fact-46 columns (trigger, signer, crypto
performed); each emitted row carries the fact tags it condenses.

    .venv/Scripts/python.exe paper/data/make_transitions.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from lifecycle.state_machine import LEGAL_TRANSITIONS  # noqa: E402

FACTS = ROOT / "paper" / "notes" / "facts-F1.md"
OUT = ROOT / "paper" / "tables" / "transitions.tex"

NAME = {
    "GRANTED": "granted",
    "REVOKED": "revoked",
    "EMERGENCY_OPEN": "emergency_open",
    "EXPIRED": "expired",
}
SHORT = {
    "granted": r"\textsc{Granted}",
    "revoked": r"\textsc{Revoked}",
    "emergency_open": r"\textsc{EmOpen}",
    "expired": r"\textsc{Expired}",
}

# Condensed from facts-F1 fact 46 (columns: trigger / signed by / crypto
# performed). Order follows the fact-46 table.
ROWS: list[tuple[str, str, str, str, str, str]] = [
    ("granted", "revoked", "Patient revokes",
     "Patient", r"Full rotation$^{a}$", "facts-F1#32, facts-F1#37, facts-F1#46"),
    ("granted", "emergency_open", r"Break-glass; reason code required",
     "Clinician", r"None$^{b}$",
     "facts-F1#14, facts-F1#30, facts-F1#36, facts-F1#46, facts-F3#46"),
    ("revoked", "emergency_open", r"As above",
     "Clinician", r"None$^{b}$", "facts-F1#36, facts-F1#46"),
    ("revoked", "granted", "Legal; no code emits it",
     "---", "None implemented", "facts-F1#35, facts-F1#46"),
    ("emergency_open", "expired", r"Timer: $\mathit{now}\ge\mathit{expires\_at}$",
     "Timer", "None; rotation follows", "facts-F1#33, facts-F1#46, facts-F1#53"),
    ("expired", "granted", "Timer, once rotation is stored and shares deposited",
     "Timer", r"Full rotation$^{a}$ before it", "facts-F1#39, facts-F1#46, facts-F1#63"),
    ("expired", "revoked",
     r"As above, if \textsc{Revoked} before; or patient revokes",
     "Timer or Patient", r"Full rotation$^{a}$",
     "facts-F1#12, facts-F1#46, facts-F1#64, facts-F1#73"),
]

# Signer words a row may name, and the key each must match in the fact-46
# "Signed by" column. A row signer of "---" stands for the fact's "n/a".
SIGNER_WORDS = {"Patient": "patient", "Clinician": "clinician", "Timer": "timer"}


def fact46_rows() -> dict[tuple[str, str], str]:
    """Map each fact-46 (from, to) pair to its lower-cased "Signed by" cell."""
    text = FACTS.read_text(encoding="utf-8")
    block = text.split("## Transition table (derived from code)", 1)[1]
    block = block.split("\n## ", 1)[0]
    rows = {}
    for m in re.finditer(
        r"^\|\s*([A-Z_]+)\s*→\s*([A-Z_]+)\s*\|[^|]*\|([^|]*)\|", block, re.M
    ):
        rows[(NAME[m.group(1)], NAME[m.group(2)])] = m.group(3).strip().lower()
    return rows


def signer_mismatches(fact_rows: dict[tuple[str, str], str]) -> list[str]:
    """Rows whose named signers differ from the fact-46 "Signed by" cell."""
    bad = []
    for frm, to, _trig, signer, _op, _src in ROWS:
        cell = fact_rows[(frm, to)]
        in_fact = {w for w, key in SIGNER_WORDS.items() if key in cell}
        if signer == "---":
            ok = cell.startswith("n/a") and not in_fact
        else:
            ok = {w for w in SIGNER_WORDS if w in signer} == in_fact
        if not ok:
            bad.append(f"{frm}->{to}: row says {signer!r}, fact says {cell!r}")
    return bad


def main() -> int:
    code = {(a.value, b.value) for a, b in LEGAL_TRANSITIONS}
    fact_rows = fact46_rows()
    facts = set(fact_rows)
    rows = {(r[0], r[1]) for r in ROWS}
    if not (code == facts == rows) or len(ROWS) != len(code):
        print(f"MISMATCH code={sorted(code)} facts={sorted(facts)} rows={sorted(rows)}")
        return 1
    bad = signer_mismatches(fact_rows)
    if bad:
        print("SIGNER MISMATCH vs facts-F1#46:\n  " + "\n  ".join(bad))
        return 1

    lines = [
        "% Generated by paper/data/make_transitions.py -- do not edit by hand.",
        "% Pairs checked equal to lifecycle.state_machine.LEGAL_TRANSITIONS and facts-F1#46;"
        " signers checked against facts-F1#46.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Legal lifecycle transitions as implemented."
        r" Any other pair is rejected before signing. Signer ``Timer'' is the timer-service key.}"
        r"  % src: facts-F1#11, facts-F1#19, facts-F1#33, facts-F1#73",
        r"\label{tab:transitions}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\renewcommand{\arraystretch}{1.1}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.14\columnwidth}"
        r">{\raggedright\arraybackslash}p{0.14\columnwidth}"
        r">{\raggedright\arraybackslash}p{0.29\columnwidth}"
        r">{\raggedright\arraybackslash}p{0.12\columnwidth}"
        r">{\raggedright\arraybackslash}p{0.23\columnwidth}@{}}",
        r"\toprule",
        r"From & To & Trigger & Signer & Key operation \\",
        r"\midrule",
    ]
    for frm, to, trig, signer, op, src in ROWS:
        lines.append(f"{SHORT[frm]} & {SHORT[to]} & {trig} & {signer} & {op} \\\\  % src: {src}")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip",
        r"\parbox{\columnwidth}{\raggedright"
        r" $^{a}$New DEK and re-encrypted record, new policy root, new emergency key"
        r" with fresh 3-of-4 shares, re-derived search index."
        r"  % src: facts-F1#37, facts-F1#40, facts-F1#46" "\n"
        r" \newline $^{b}$3-of-4 combine; DEK unwrapped and delivered by a KEM to the"
        r" clinician's ElGamal key; nothing is re-keyed (Section~\ref{sec:breakglass})."
        r"  % src: facts-F1#36, facts-F3#46" "\n"
        r" \newline \textsc{EmOpen} = \textsc{Emergency\_Open}.}",
        r"\end{table}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(ROWS)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
