"""Generate paper/tables/bench.tex from the benchmark results (W6).

Reads bench/results/benchmark_summary.csv (latencies, ms) and
bench/results/environment.json (machine, deployment path) and writes the
booktabs table labelled tab:bench. Numbers are only formatted (three
significant figures) from the CSV strings; nothing is typed by hand. Run from
the repo root:

    .venv/Scripts/python.exe paper/data/make_bench_table.py
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "bench" / "results"
OUT = ROOT / "paper" / "tables" / "bench.tex"

# Paper labels and the path each benchmark exercises (facts-F7#21-24, #26-32).
# Order follows the CSV; a benchmark missing from this map is an error.
LABELS = {
    "threshold_reconstruction": ("Shamir combine (3-of-4)", "in-proc.", 26),
    "rewrap_cost": ("DEK re-wrap (one DEK)", "in-proc.", 27),
    "revocation_latency": ("Revocation (library call)", "in-proc.", 28),
    "pre_reencryption_component": ("PRE re-encrypt (demo group)", "in-proc.", 29),
    "cross_facility_latency": ("Cross-facility discovery", "HTTP+DB", 30),
    "emergency_search_latency": ("Emergency search", "HTTP+DB", 31),
    "audit_verification": ("Audit chain verification", "DB read", 32),
}


def fmt(value: str) -> str:
    """Three significant figures, plain decimal (no exponent)."""
    x = float(value)
    exponent = int(f"{x:e}".split("e")[1])
    return f"{x:.{max(0, 2 - exponent)}f}"


def main() -> None:
    with (RESULTS / "benchmark_summary.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    env = json.loads((RESULTS / "environment.json").read_text(encoding="utf-8"))

    iterations = {r["iterations"] for r in rows}
    warmups = {r["warmup"] for r in rows}
    if len(iterations) != 1 or len(warmups) != 1:
        raise SystemExit("iterations/warm-up differ between benchmarks; caption would lie")
    if {r["metric"] for r in rows} != {"latency_ms"}:
        raise SystemExit("unexpected metric in benchmark_summary.csv")
    (n,), (w,) = iterations, warmups

    body = []
    for r in rows:
        name, path, fact = LABELS[r["benchmark"]]
        body.append(
            f"{name} & {path} & {fmt(r['median_ms'])} & {fmt(r['p95_ms'])} \\\\"
            f"  % src: facts-F7#{fact}\n"
            f"  % (benchmark_summary.csv row {r['benchmark']})"
        )

    cpu = env["cpu"].split(",")[0]
    caption = (
        f"Latency in ms (median and p95 of $n={n}$ timed calls after {w} warm-up "
        f"calls). Machine: {cpu}, {env['cores']} logical cores, "
        f"{env['ram_gb']}\\,GB RAM, Python {env['python']}; deployment path "
        # \textnormal keeps IEEEtran's small-caps caption from uppercasing it.
        f"\\textnormal{{\\texttt{{{env['deployment_path']}}}}}. HTTP rows include transport."
    )
    lines = [
        "% Generated by paper/data/make_bench_table.py from",
        "% bench/results/benchmark_summary.csv and bench/results/environment.json.",
        "% Do not edit by hand; re-run the script.",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{{caption}}}  % src: facts-F7#7, facts-F7#9, facts-F7#14, facts-F7#15, facts-F7#22",
        "\\label{tab:bench}",
        "\\footnotesize",
        "\\begin{tabular}{@{}llrr@{}}",
        "\\toprule",
        "Operation & Path & Median & p95 \\\\",
        "\\midrule",
        *body,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(body)} rows)")


if __name__ == "__main__":
    main()
