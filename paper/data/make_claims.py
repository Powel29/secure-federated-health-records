"""Generate paper/tables/claims.tex (label tab:claims) from the live claims run.

Source: paper/notes/live-claims-raw.txt, the verbatim output of
`python -m tests.security.claims --table` (facts-live). Statuses and claim
statements are copied from that file, never retyped. Test counts are the
number of `<br>`-separated node ids in the Module/System columns ("none" = 0).

Deterministic rewriting applied to the printed statement (and only this):
  * LaTeX special characters are escaped.
No statement is abbreviated.

The commit is not printed in the raw file; it is recorded in facts-live
("Run metadata": `git rev-parse --short HEAD` = 57a1a8c) and checked here
against the raw file's START date.

    .venv/Scripts/python.exe paper/data/make_claims.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "paper" / "notes" / "live-claims-raw.txt"
OUT = ROOT / "paper" / "tables" / "claims.tex"

RUN_SHA = "57a1a8c"  # facts-live, "Run metadata" (commit of the live run)
RUN_DATE = "2026-10-21"  # must match the START line of the raw file
EXPECTED_SYSTEM_TOTAL = 35  # facts-live#12

_TEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex(s: str) -> str:
    return "".join(_TEX_ESCAPES.get(c, c) for c in s)


def count_tests(cell: str) -> int:
    cell = cell.strip()
    if cell == "none":
        return 0
    return len([p for p in cell.split("<br>") if p.strip()])


def parse() -> tuple[str, list[dict[str, str | int]]]:
    text = RAW.read_text(encoding="utf-8")
    m = re.search(r"^START (\d{4}-\d{2}-\d{2})", text, re.M)
    if not m:
        raise SystemExit("raw file has no START line")
    if m.group(1) != RUN_DATE:
        raise SystemExit(f"raw run date {m.group(1)} != {RUN_DATE}")
    if "EXIT=0" not in text:
        raise SystemExit("raw claims run did not exit 0")
    rows = []
    for line in text.splitlines():
        if not re.match(r"^\| C\d+ \|", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 5:
            raise SystemExit(f"unexpected row shape: {line[:60]}")
        claim, statement, status, module, system = cells
        rows.append(
            {
                "claim": claim,
                "statement": statement,
                "status": status,
                "module": count_tests(module),
                "system": count_tests(system),
            }
        )
    if [r["claim"] for r in rows] != [f"C{i}" for i in range(1, 12)]:
        raise SystemExit("expected exactly C1..C11 in order")
    return m.group(1), rows


def main() -> None:
    date, rows = parse()
    total_sys = sum(int(r["system"]) for r in rows)
    total_mod = sum(int(r["module"]) for r in rows)
    if total_sys != EXPECTED_SYSTEM_TOTAL:
        raise SystemExit(f"system-test total {total_sys} != {EXPECTED_SYSTEM_TOTAL}")
    out = [
        "% Generated by paper/data/make_claims.py from paper/notes/live-claims-raw.txt.",
        "% Do not edit by hand. Statements and statuses are verbatim from the live",
        "% `python -m tests.security.claims --table` run (only LaTeX-escaped).",
        r"\begin{table}[!t]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        (
            r"\caption{Security claims C1--C11, live claims run "
            f"{date} at commit \\textnormal{{\\texttt{{{RUN_SHA}}}}}. "
            r"Status is computed from the system-level tests only; "
            r"Sys./Mod.\ count the system- and module-level tests tagged with the claim.}"
        ),
        "% src: " + ", ".join(f"facts-live#{i}" for i in range(1, 14)),
        r"\label{tab:claims}",
        r"\begin{tabular}{@{}l p{0.64\columnwidth} l r r@{}}",
        r"\toprule",
        r"ID & Statement (as printed by the run) & Status & Sys. & Mod. \\",
        r"\midrule",
    ]
    for r in rows:
        out.append(
            f"{r['claim']} & {tex(str(r['statement']))} & {tex(str(r['status']))} & "
            f"{r['system']} & {r['module']} \\\\"
        )
    out += [
        r"\midrule",
        f"\\multicolumn{{3}}{{@{{}}l}}{{Total}} & {total_sys} & {total_mod} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} claims, {total_sys} system, {total_mod} module tests)")


if __name__ == "__main__":
    main()
